-- =========================================
-- DATABASE LAUNDRYKU
-- PostgreSQL - Aiven
--
-- Berkas ini aman dijalankan berulang pada database yang sudah berisi data:
--   psql "$DATABASE_URL" -f database/schema.sql
--
-- Struktur yang sudah ada tidak ditimpa. Tabel dibuat bila belum ada, kolom
-- pembayaran ditambahkan bila belum ada, dan pemeriksaan di bagian akhir
-- hanya membaca.
-- =========================================

BEGIN;

-- =========================================
-- 1. TABEL USERS
-- Menyimpan akun Admin dan Customer
-- =========================================

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_users PRIMARY KEY (id),

    CONSTRAINT chk_users_role
        CHECK (role IN ('ADMIN', 'CUSTOMER')),

    CONSTRAINT chk_users_name_not_empty
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT chk_users_email_not_empty
        CHECK (LENGTH(TRIM(email)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower
ON users (LOWER(email));


-- =========================================
-- 2. TABEL SERVICES
-- Menyimpan layanan laundry
-- =========================================

CREATE TABLE IF NOT EXISTS services (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    price_per_kg NUMERIC(10,2) NOT NULL,
    duration VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_services PRIMARY KEY (id),

    CONSTRAINT chk_services_name_not_empty
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT chk_services_price_positive
        CHECK (price_per_kg > 0),

    CONSTRAINT chk_services_duration_not_empty
        CHECK (LENGTH(TRIM(duration)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_services_name
ON services (name);


-- =========================================
-- 3. TABEL ORDERS
-- Menyimpan pesanan pelanggan
-- =========================================

CREATE TABLE IF NOT EXISTS orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    user_id INTEGER NOT NULL,
    service_id INTEGER NOT NULL,

    estimated_weight NUMERIC(8,2) NOT NULL,
    actual_weight NUMERIC(8,2),

    price_per_kg NUMERIC(10,2) NOT NULL,
    total_price NUMERIC(12,2),

    status VARCHAR(30) NOT NULL
        DEFAULT 'PENDING_CONFIRMATION',

    photo_url TEXT,

    -- Pembayaran. Tunai baru lunas setelah admin mengonfirmasi uangnya
    -- diterima, sedangkan metode lain langsung dianggap lunas saat pesanan
    -- dibuat. Ketiganya boleh kosong untuk pesanan lama yang belum mencatat
    -- metode pembayaran.
    payment_method VARCHAR(20),
    payment_status VARCHAR(20),
    paid_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_orders PRIMARY KEY (id),

    CONSTRAINT fk_orders_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_orders_service
        FOREIGN KEY (service_id)
        REFERENCES services(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_orders_estimated_weight_positive
        CHECK (estimated_weight > 0),

    CONSTRAINT chk_orders_actual_weight_positive
        CHECK (
            actual_weight IS NULL
            OR actual_weight > 0
        ),

    CONSTRAINT chk_orders_price_positive
        CHECK (price_per_kg > 0),

    CONSTRAINT chk_orders_total_and_actual_weight
        CHECK (
            (actual_weight IS NULL AND total_price IS NULL)
            OR
            (
                actual_weight IS NOT NULL
                AND total_price IS NOT NULL
                AND total_price >= 0
            )
        ),

    CONSTRAINT chk_orders_status
        CHECK (
            status IN (
                'PENDING_CONFIRMATION',
                'CONFIRMED',
                'WASHING',
                'READY_FOR_PICKUP',
                'COMPLETED',
                'CANCELLED'
            )
        ),

    CONSTRAINT chk_orders_payment_method
        CHECK (
            payment_method IS NULL
            OR payment_method IN (
                'CASH',
                'QRIS',
                'BANK_TRANSFER',
                'EWALLET'
            )
        ),

    CONSTRAINT chk_orders_payment_status
        CHECK (
            payment_status IS NULL
            OR payment_status IN ('UNPAID', 'PAID')
        ),

    -- Waktu pembayaran hanya boleh terisi bila statusnya memang sudah lunas.
    CONSTRAINT chk_orders_paid_at
        CHECK (
            (payment_status IS NULL AND paid_at IS NULL)
            OR (payment_status = 'UNPAID' AND paid_at IS NULL)
            OR (payment_status = 'PAID' AND paid_at IS NOT NULL)
        )
);

CREATE INDEX IF NOT EXISTS idx_orders_user_created
ON orders (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_orders_service_id
ON orders (service_id);

CREATE INDEX IF NOT EXISTS idx_orders_status_created
ON orders (status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_orders_payment_status
ON orders (payment_status, created_at DESC);


-- =========================================
-- 4. PEMBARUAN UNTUK DATABASE YANG SUDAH BERISI
--
-- CREATE TABLE IF NOT EXISTS di atas tidak menambah kolom ke tabel yang
-- sudah terlanjur dibuat sebelum kolom pembayaran ada. Bagian ini menutup
-- selisih itu tanpa menyentuh data yang sudah tersimpan.
-- =========================================

-- Aplikasi mobile mengirim metode pembayaran saat pesanan dibuat, dan admin
-- memakai status pembayaran untuk mengonfirmasi uang tunai. Tanpa tiga kolom
-- ini, pesanan dari aplikasi ditolak dengan "kolom payment_method tidak ada".
ALTER TABLE orders
    ADD COLUMN IF NOT EXISTS payment_method VARCHAR(20),
    ADD COLUMN IF NOT EXISTS payment_status VARCHAR(20),
    ADD COLUMN IF NOT EXISTS paid_at TIMESTAMPTZ;

-- ADD COLUMN IF NOT EXISTS melewati kolom yang sudah ada, termasuk
-- constraint-nya, jadi aturan di bawah hanya ditambahkan bila belum ada.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'chk_orders_payment_method'
    ) THEN
        ALTER TABLE orders
            ADD CONSTRAINT chk_orders_payment_method
            CHECK (
                payment_method IS NULL
                OR payment_method IN ('CASH', 'QRIS', 'BANK_TRANSFER', 'EWALLET')
            );
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'chk_orders_payment_status'
    ) THEN
        ALTER TABLE orders
            ADD CONSTRAINT chk_orders_payment_status
            CHECK (
                payment_status IS NULL
                OR payment_status IN ('UNPAID', 'PAID')
            );
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'chk_orders_paid_at'
    ) THEN
        ALTER TABLE orders
            ADD CONSTRAINT chk_orders_paid_at
            CHECK (
                (payment_status IS NULL AND paid_at IS NULL)
                OR (payment_status = 'UNPAID' AND paid_at IS NULL)
                OR (payment_status = 'PAID' AND paid_at IS NOT NULL)
            );
    END IF;
END
$$;

-- Layanan yang masih dipakai pesanan tidak boleh terhapus, sehingga riwayat
-- pesanan pelanggan tetap utuh.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_orders_service'
    ) THEN
        ALTER TABLE orders
            ADD CONSTRAINT fk_orders_service
            FOREIGN KEY (service_id)
            REFERENCES services(id)
            ON UPDATE CASCADE
            ON DELETE RESTRICT;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_orders_user'
    ) THEN
        ALTER TABLE orders
            ADD CONSTRAINT fk_orders_user
            FOREIGN KEY (user_id)
            REFERENCES users(id)
            ON UPDATE CASCADE
            ON DELETE RESTRICT;
    END IF;
END
$$;

-- Keempat index ini dibuat dengan IF NOT EXISTS, jadi aman diulang.
CREATE INDEX IF NOT EXISTS idx_orders_user_created
ON orders (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_orders_service_id
ON orders (service_id);

CREATE INDEX IF NOT EXISTS idx_orders_status_created
ON orders (status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_orders_payment_status
ON orders (payment_status, created_at DESC);

COMMIT;


-- =========================================
-- 5. PEMERIKSAAN DATABASE
--
-- Bagian ini hanya membaca, supaya berkasnya tetap aman dijalankan pada
-- database berisi data tanpa mengubah apa pun.
-- =========================================

SELECT current_database();

SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_type = 'BASE TABLE'
  AND table_name IN ('users', 'services', 'orders')
ORDER BY table_name;


-- =========================================
-- 6. MEMERIKSA RELASI DAN CONSTRAINT
-- =========================================

SELECT
    tc.table_name,
    tc.constraint_name,
    tc.constraint_type
FROM information_schema.table_constraints AS tc
WHERE tc.table_schema = 'public'
  AND tc.table_name IN (
      'users',
      'services',
      'orders'
  )
ORDER BY
    tc.table_name,
    tc.constraint_type;


-- =========================================
-- 7. MEMERIKSA KOLOM TABEL ORDERS
-- =========================================

SELECT
    column_name,
    data_type,
    is_nullable,
    column_default
FROM information_schema.columns
WHERE table_schema = 'public'
  AND table_name = 'orders'
ORDER BY ordinal_position;
